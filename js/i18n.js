export const languageOptions = ['auto', 'en', 'uk', 'ru'];
export function normalizeLocale(locale) {
  return typeof locale === 'string' ? locale.trim().toLowerCase().replaceAll('_', '-').split('-')[0] : '';
}
export function detectLanguage(device = globalThis.navigator) {
  const locales = Array.isArray(device?.languages) ? device.languages.filter(v => typeof v === 'string' && v.trim()) : [];
  // The first preferred device language controls Auto; unsupported languages fall back to English.
  const locale = normalizeLocale(locales[0] || device?.language);
  return Object.hasOwn(translations, locale) ? locale : 'en';
}
let language = detectLanguage();
let plurals = new Intl.PluralRules(language);
export const getLanguage = () => language;
export function setLanguage(preference = 'auto', device = globalThis.navigator) {
  language = preference !== 'auto' && Object.hasOwn(translations, preference) ? preference : detectLanguage(device);
  plurals = new Intl.PluralRules(language);
  if (globalThis.document) document.documentElement.lang = language;
  return language;
}
export function t(key, values = {}) {
  let value = Object.hasOwn(translations[language], key) ? translations[language][key] : Object.hasOwn(translations.en, key) ? translations.en[key] : undefined;
  if (value === undefined) return key;
  if (typeof value === 'object') value = value[plurals.select(values.count)] || value.other;
  return value.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
}
export const minesText = count => t('mineCount', { count });
export const numberText = value => new Intl.NumberFormat(language).format(value);
export function translateDOM(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const attribute of ['aria-label', 'title', 'content']) {
    root.querySelectorAll(`[data-i18n-${attribute}]`).forEach(el => el.setAttribute(attribute, t(el.getAttribute(`data-i18n-${attribute}`))));
  }
  root.querySelectorAll('[data-mine-count]').forEach(el => { el.textContent = minesText(Number(el.dataset.mineCount)); });
}
